import AppKit
import ImageIO
import UniformTypeIdentifiers
import Vision

/// Watches NSPasteboard.changeCount (a cheap call) and reads data only when it changes.
/// Polling is coalesced via timer tolerance and suspended while the system sleeps.
final class PasteboardMonitor {
    static let ownType = NSPasteboard.PasteboardType("com.kamaliev.clipvault.own")

    /// Types set by password managers and other apps that mark content as sensitive/transient
    /// (see nspasteboard.org).
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        ownType.rawValue,
    ]

    static let textTypes = ["public.utf8-plain-text", "public.rtf", "public.html"]
    static let imageTypes = ["public.png", "public.tiff", "public.jpeg", "com.compuserve.gif"]
    static let fileURLType = "public.file-url"

    private let pasteboard = NSPasteboard.general
    private let store: Store
    private let maxBytes: Int
    private let queue = DispatchQueue(label: "clipvault.ingest", qos: .utility)
    private var lastChangeCount: Int
    private var timer: Timer?
    private var observers: [NSObjectProtocol] = []

    var paused = false
    /// Recognize text in copied images (on-device Vision) so they can be found by search.
    var recognizeText = true
    var onAdded: (() -> Void)?

    init(store: Store, maxBytes: Int) {
        self.store = store
        self.maxBytes = maxBytes
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        let nc = NSWorkspace.shared.notificationCenter
        for name in [NSWorkspace.willSleepNotification, NSWorkspace.screensDidSleepNotification,
                     NSWorkspace.sessionDidResignActiveNotification] {
            observers.append(nc.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
                self?.stopTimer()
            })
        }
        for name in [NSWorkspace.didWakeNotification, NSWorkspace.screensDidWakeNotification,
                     NSWorkspace.sessionDidBecomeActiveNotification] {
            observers.append(nc.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
                self?.startTimer()
            })
        }
        startTimer()
    }

    /// Marks the current pasteboard contents as seen (used after we write to it ourselves).
    func skipCurrent() {
        lastChangeCount = pasteboard.changeCount
    }

    private func startTimer() {
        guard timer == nil else { return }
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.tick() }
        t.tolerance = 0.3
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func stopTimer() {
        timer?.invalidate()
        timer = nil
    }

    private func tick() {
        let cc = pasteboard.changeCount
        guard cc != lastChangeCount else { return }
        lastChangeCount = cc
        guard !paused else { return }
        capture()
    }

    private func capture() {
        guard let items = pasteboard.pasteboardItems, !items.isEmpty else { return }
        let allTypes = Set(items.flatMap { $0.types.map(\.rawValue) })
        guard allTypes.isDisjoint(with: Self.ignoredTypes) else { return }

        let hasFiles = allTypes.contains(Self.fileURLType)
        var reps: [ClipRep] = []
        var total = 0
        for (index, item) in items.enumerated() {
            let types = item.types.map(\.rawValue)
            for type in types where Self.wanted(type, in: types, hasFiles: hasFiles) {
                guard let data = item.data(forType: .init(type)), !data.isEmpty else { continue }
                total += data.count
                if total > maxBytes { return }
                reps.append(ClipRep(item: UInt32(index), uti: type, data: data))
            }
        }
        guard !reps.isEmpty else { return }

        let sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName
        let imageOnly = !reps.contains { Self.textTypes.contains($0.uti) || $0.uti == Self.fileURLType }
        let store = self.store
        let recognize = recognizeText
        queue.async { [weak self] in
            let image = imageOnly ? reps.first { Self.imageTypes.contains($0.uti) } : nil
            let thumb = image.flatMap { Self.thumbnail($0.data) }
            let ocr = recognize ? image.flatMap { Self.recognizeText($0.data) } : nil
            do {
                if try store.add(clip: NewClip(reps: reps, sourceApp: sourceApp, thumbnail: thumb, ocrText: ocr)) != nil {
                    DispatchQueue.main.async { self?.onAdded?() }
                }
            } catch {
                NSLog("clipvault: failed to store clip: \(error)")
            }
        }
    }

    private static func wanted(_ type: String, in types: [String], hasFiles: Bool) -> Bool {
        if hasFiles {
            // Finder also puts large icon images on the pasteboard; paths are enough.
            return type == fileURLType || type == "public.utf8-plain-text"
        }
        if type == "public.tiff" && types.contains("public.png") { return false }
        return textTypes.contains(type) || imageTypes.contains(type)
    }

    static func recognizeText(_ data: Data) -> String? {
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.usesLanguageCorrection = true
        request.automaticallyDetectsLanguage = true
        do {
            try VNImageRequestHandler(data: data, options: [:]).perform([request])
        } catch {
            return nil
        }
        let lines = (request.results ?? []).compactMap { $0.topCandidates(1).first?.string }
        return lines.isEmpty ? nil : lines.joined(separator: "\n")
    }

    static func thumbnail(_ data: Data, maxPixels: Int = 160) -> Data? {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let opts: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixels,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary) else { return nil }
        let out = NSMutableData()
        guard let dst = CGImageDestinationCreateWithData(out, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dst, cg, nil)
        return CGImageDestinationFinalize(dst) ? out as Data : nil
    }
}
