pub const UTI_TEXT: &str = "public.utf8-plain-text";
pub const UTI_RTF: &str = "public.rtf";
pub const UTI_HTML: &str = "public.html";
pub const UTI_FILE_URL: &str = "public.file-url";
pub const IMAGE_UTIS: &[&str] = &[
    "public.png",
    "public.tiff",
    "public.jpeg",
    "com.compuserve.gif",
];

#[derive(Debug, Clone, Copy, PartialEq, Eq, uniffi::Enum)]
pub enum ClipKind {
    Text,
    Rtf,
    Html,
    Image,
    Files,
}

impl ClipKind {
    pub fn to_i64(self) -> i64 {
        match self {
            ClipKind::Text => 0,
            ClipKind::Rtf => 1,
            ClipKind::Html => 2,
            ClipKind::Image => 3,
            ClipKind::Files => 4,
        }
    }

    pub fn from_i64(v: i64) -> Self {
        match v {
            1 => ClipKind::Rtf,
            2 => ClipKind::Html,
            3 => ClipKind::Image,
            4 => ClipKind::Files,
            _ => ClipKind::Text,
        }
    }
}

/// One pasteboard representation. `item` groups representations into NSPasteboardItems
/// (e.g. several copied files are several items).
#[derive(Debug, Clone, PartialEq, Eq, uniffi::Record)]
pub struct ClipRep {
    pub item: u32,
    pub uti: String,
    pub data: Vec<u8>,
}

#[derive(Debug, Clone, uniffi::Record)]
pub struct NewClip {
    pub reps: Vec<ClipRep>,
    pub source_app: Option<String>,
    /// Small PNG thumbnail for images, generated by the app.
    pub thumbnail: Option<Vec<u8>>,
}

#[derive(Debug, Clone, PartialEq, Eq, uniffi::Record)]
pub struct ClipSummary {
    pub id: i64,
    pub kind: ClipKind,
    pub preview: String,
    pub source_app: Option<String>,
    pub created_at: i64,
    pub size: u64,
    pub has_thumbnail: bool,
}
